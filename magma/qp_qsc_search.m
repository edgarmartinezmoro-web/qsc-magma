// =====================================================================
//  qp_qsc_search.m
//  Search for quasi-polycyclic QSCs via Theorem theo:main3 of the paper
//  (annihilator-CSS in physical coordinates + block synchronisation),
//  together with quasi-cyclic / quasi-constacyclic baselines.
//
//  Usage (inside Magma):
//      load "qp_qsc_search.m";
//      B := RunSearch(2, [10..14], 2, 50, 1, 3);
//            // q, degrees m, index l, trials, extra generators, min window
//      PrintBest(B);
//      SaveBest(B, "results_q2_l2.txt");
//
//  Conventions:
//    A = F_q[x]/<f>, deg f = m, QP codes C <= A^l, N = l*m, Psi = coefficient expansion.
//    X3 = Psi(C3)       : bit-flip code (physical coordinates, QP)
//    X2 = Psi(C2) * G   : phase-flip code, G = I_l (x) Hankel Gram matrix
//    C3° <= C2          : guarantees Dual(X2) subset X3   (Theorem teo:twist)
//    K  = dim C3 + dim C2 - N
//    Sync block = block 1: pi_1(C3) = <g3>,  C1 = <g1>,  g1 | g3 | f,
//                 window a_l + a_r < ord(g3/g1), cost |s|*rho(f) in block 1 only.
//
//  NOTE: the results in results/ were produced with RunGalindo (below). Test RunSearch on a
//        small case first (e.g. RunSearch(2, [6], 2, 5, 1, 2)). The check "Dual(X2) subset X3" is asserted.
// =====================================================================

// ---------- polynomial utilities ------------------------------------

function MonicDivisors(f)
    P := Parent(f);
    divs := [ P!1 ];
    for fa in Factorization(f) do
        divs := [ d*fa[1]^j : d in divs, j in [0..fa[2]] ];
    end for;
    return divs;
end function;

// order of g: least e > 0 with g | x^e - 1 (requires g(0) <> 0)
function PolyOrder(g)
    P := Parent(g); F := BaseRing(P); p := Characteristic(F);
    if Degree(g) eq 0 then return 1; end if;
    e := 1;
    for fa in Factorization(g) do
        h := fa[1]; mult := fa[2];
        if Degree(h) eq 1 then
            o := Order(-Coefficient(h, 0));
        else
            K<a> := ext< F | h >;
            o := Order(a);
        end if;
        t := 0; while p^t lt mult do t +:= 1; end while;
        e := Lcm(e, o * p^t);
    end for;
    return e;
end function;

// twisted acyclicity rho(f): number of nonzero f_1, ..., f_{m-1}
function Rho(f)
    return #[ i : i in [1..Degree(f)-1] | Coefficient(f, i) ne 0 ];
end function;

function Family(f)
    if Rho(f) eq 0 then
        if Coefficient(f, 0) eq -1 then return "QC"; else return "QconstaC"; end if;
    end if;
    return "QP(rho=" cat IntegerToString(Rho(f)) cat ")";
end function;

// binomials x^m - lambda and trinomials x^m + a x^i + b
function PolyList(F, m)
    P<x> := PolynomialRing(F);
    L := [ x^m - lam : lam in F | lam ne 0 ];
    for i in [1..m-1] do
        for a in F do for b in F do
            if a ne 0 and b ne 0 then Append(~L, x^m + a*x^i + b); end if;
        end for; end for;
    end for;
    return L;
end function;

// ---------- vectors, codes, Gram matrix -----------------------------

function CoeffVec(a, f)
    F := BaseRing(Parent(f)); m := Degree(f);
    c := Eltseq(a mod f);
    return c cat [ F!0 : t in [#c+1..m] ];
end function;

// F_q-code Psi(M) of the A-submodule M of A^l generated by gens (each gen = [p_1..p_l])
function QPCode(gens, f, l)
    P := Parent(f); F := BaseRing(P); m := Degree(f); x := P.1;
    rows := [];
    for g in gens do
        for j in [0..m-1] do
            v := [];
            for i in [1..l] do v cat:= CoeffVec(x^j * g[i], f); end for;
            Append(~rows, v);
        end for;
    end for;
    if #rows eq 0 then return ZeroCode(F, l*m); end if;
    return LinearCode(Matrix(F, #rows, l*m, &cat rows));
end function;

function PolyCode(g, f)
    return QPCode([ [g] ], f, 1);
end function;

// Hankel Gram matrix of the annihilator form
function AnnGram(f)
    P := Parent(f); F := BaseRing(P); m := Degree(f); x := P.1;
    return Matrix(F, m, m, [ Coefficient((x^(i+j)) mod f, 0) : i, j in [0..m-1] ]);
end function;

function BigGram(f, l)
    F := BaseRing(Parent(f));
    return KroneckerProduct(IdentityMatrix(F, l), AnnGram(f));
end function;

// Psi(C°) = Dual(Psi(C)) * G^(-1)     (Theorem teo:twist)
function AnnDual(X, f, l)
    F := BaseRing(Parent(f));
    D := Dual(X);
    if Dimension(D) eq 0 then return ZeroCode(F, l*Degree(f)); end if;
    return LinearCode(GeneratorMatrix(D) * BigGram(f, l)^(-1));
end function;

// X * G  (the twisted phase-flip code)
function Twist(X, f, l)
    if Dimension(X) eq 0 then return X; end if;
    return LinearCode(GeneratorMatrix(X) * BigGram(f, l));
end function;

// rows of an F_q-code  ->  elements of A^l (sequences of l polynomials)
function RowsToGens(X, f, l)
    P := Parent(f); m := Degree(f);
    if Dimension(X) eq 0 then return []; end if;
    out := [];
    for r in Rows(GeneratorMatrix(X)) do
        w := Eltseq(r);
        Append(~out, [ P!(w[(i-1)*m+1 .. i*m]) : i in [1..l] ]);
    end for;
    return out;
end function;

// sanity check: Psi(C°) must be an A-module (closed under x in every block)
function IsModule(X, f, l)
    P := Parent(f); F := BaseRing(P); m := Degree(f); x := P.1;
    for g in RowsToGens(X, f, l) do
        v := &cat[ CoeffVec(x * g[i], f) : i in [1..l] ];
        if not (Vector(F, v) in X) then return false; end if;
    end for;
    return true;
end function;

// ---------- random generators ---------------------------------------

function RandPoly(F, P, m)
    return P![ Random(F) : i in [1..m] ];
end function;

// upper-triangular generators with diagonal diag = [d_1, ..., d_l]
function RandomTriangular(diag, f, l)
    P := Parent(f); F := BaseRing(P); m := Degree(f);
    gens := [];
    for r in [1..l] do
        g := [ P!0 : i in [1..l] ];
        g[r] := diag[r];
        for c in [r+1..l] do g[c] := RandPoly(F, P, m); end for;
        Append(~gens, g);
    end for;
    return gens;
end function;

// a random element of A^l, multiplied by a random divisor of f (keeps dimension moderate)
function RandomGen(divs, f, l)
    P := Parent(f); F := BaseRing(P); m := Degree(f);
    d := Random(divs);
    return [ (d * RandPoly(F, P, m)) mod f : i in [1..l] ];
end function;

// ---------- the search ------------------------------------------------

// value = < min(dX,dZ), dX, dZ, d1, window, rho, f, gens3, gens2 >
function IsBetter(a, b)
    for t in [1..5] do
        if a[t] ne b[t] then return a[t] gt b[t]; end if;
    end for;
    return false;
end function;

function RunSearch(q, degrees, l, trials, extra, minwindow)
    F := GF(q);
    Best := AssociativeArray();
    for m in degrees do
        N := l*m;
        for f in PolyList(F, m) do
            divs := MonicDivisors(f);
            for g3 in divs do
                // synchronisation block: best g1 | g3 (proper) with ord(g3/g1) >= minwindow
                found := false; best1 := < 0, 0, Parent(f)!1 >;
                for g1 in divs do
                    if Degree(g1) ge Degree(g3) or not IsDivisibleBy(g3, g1) then continue; end if;
                    w := PolyOrder(g3 div g1);
                    if w lt minwindow then continue; end if;
                    d1 := MinimumDistance(PolyCode(g1, f));
                    if (not found) or d1 gt best1[1] or (d1 eq best1[1] and w gt best1[2]) then
                        best1 := < d1, w, g1 >; found := true;
                    end if;
                end for;
                if not found then continue; end if;
                for tup in CartesianPower(Set(divs), l-1) do
                    diag := [ g3 ] cat [ tup[i] : i in [1..l-1] ];
                    for t in [1..trials] do
                        gens3 := RandomTriangular(diag, f, l);
                        X3 := QPCode(gens3, f, l);
                        k3 := Dimension(X3);
                        // C2 := C3° + random generators
                        gens2 := RowsToGens(AnnDual(X3, f, l), f, l)
                                 cat [ RandomGen(divs, f, l) : e in [1..extra] ];
                        C2 := QPCode(gens2, f, l);
                        k2 := Dimension(C2);
                        K := k3 + k2 - N;
                        if K le 0 then continue; end if;
                        X2 := Twist(C2, f, l);
                        assert Dual(X2) subset X3;                  // Theorem theo:cssanh
                        dX := MinimumDistance(X3);
                        dZ := MinimumDistance(X2);
                        key := < N, K, Family(f) >;
                        cand := < Min(dX, dZ), dX, dZ, best1[1], best1[2], Rho(f), f, gens3, gens2 >;
                        if (not IsDefined(Best, key)) or IsBetter(cand, Best[key]) then
                            Best[key] := cand;
                        end if;
                    end for;
                end for;
            end for;
        end for;
    end for;
    return Best;
end function;

procedure PrintBest(Best)
    keys := Sort(SetToSequence(Keys(Best)),
                 func< a, b | a[1] ne b[1] select a[1] - b[1] else a[2] - b[2] >);
    for key in keys do
        r := Best[key];
        printf "[[%o,%o]] %o : d=min(dX,dZ)=%o (dX=%o, dZ=%o)  sync: d1=%o, a_l+a_r<%o, rho=%o  f=%o\n",
               key[1], key[2], key[3], r[1], r[2], r[3], r[4], r[5], r[6], r[7];
    end for;
end procedure;

procedure SaveBest(Best, filename)
    keys := Sort(SetToSequence(Keys(Best)),
                 func< a, b | a[1] ne b[1] select a[1] - b[1] else a[2] - b[2] >);
    for key in keys do
        r := Best[key];
        fprintf filename, "[[%o,%o]] %o d=%o dX=%o dZ=%o d1=%o win=%o rho=%o f=%o\n  gens3=%o\n  gens2=%o\n",
                key[1], key[2], key[3], r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9];
    end for;
end procedure;

// =====================================================================
//  STRUCTURED SEARCH (Galindo-type, annihilator version), Lemma lem:exp:annGalindo
//
//  C = < (g, k g), (0, h) > <= A^2,  g | h,  h^2 | f   ==>   C° <= C,
//  hence (Psi(C), Psi(C) G) is a CSS pair (Theorem theo:cssanh):
//      [[2m, 2(m - deg g - deg h)]],  dX = d(Psi(C)),  dZ = d(Psi(C) G).
//  Sync block = block 1:  pi_1(C) = <g>,  marker g1 | g,  window a_l + a_r < ord(g/g1).
//  For f = x^m - lambda: rho = 0 with the lambda-twisted padding (no virtual errors).
//
//  Usage:
//      load "qp_qsc_search.m";
//      // quasi-constacyclic, q=5, m=10 and 20, all lambda (lambda = 1 is the QC baseline)
//      B := RunGalindo(5, [10, 20], "consta", 30, 3);  PrintBest(B);
//      // repeated-root trinomials f(x) = t(x)^p, e.g. to compare with Du-Ma-Liu [[50,4,4]]_5
//      B := RunGalindo(5, [25], "reptri", 30, 3);     PrintBest(B);
//      // only the targets of Du-Ma-Liu Table 1:
//      CompareDuMaLiu(30);
// =====================================================================

// is lambda an m-th power in F_q^* ?  (if yes, x^m - lambda is monomially equivalent to QC)
function IsMthPower(lam, m)
    F := Parent(lam); q := #F;
    return lam^((q-1) div Gcd(m, q-1)) eq 1;
end function;

// family "consta": x^m - lambda for lambda = 1 and all lambda that are NOT m-th powers
// family "reptri": trinomials x^m + a x^i + b with a repeated factor (h^2 | f possible)
function FList(F, m, fam)
    P<x> := PolynomialRing(F);
    if fam eq "consta" then
        return [ x^m - 1 ] cat [ x^m - lam : lam in F | lam ne 0 and not IsMthPower(lam, m) ];
    end if;
    L := [];
    for i in [1..m-1] do for a in F do for b in F do
        if a eq 0 or b eq 0 then continue; end if;
        f := x^m + a*x^i + b;
        if exists{ fa : fa in Factorization(f) | fa[2] ge 2 } then Append(~L, f); end if;
    end for; end for; end for;
    return L;
end function;

// "half" divisors of f: products of irreducible factors with exponent <= e_i div 2
// (exactly the monic h with h^2 | f)
function HalfDivisors(f)
    P := Parent(f);
    L := [ P!1 ];
    for fa in Factorization(f) do
        L := [ d*fa[1]^j : d in L, j in [0..fa[2] div 2] ];
    end for;
    return L;
end function;

// random monic divisor of h
function RandomSubDivisor(h)
    P := Parent(h);
    if Degree(h) eq 0 then return P!1; end if;
    d := P!1;
    for fa in Factorization(h) do d *:= fa[1]^Random(0, fa[2]); end for;
    return d;
end function;

// number of pairs (g,h) with g | h and h^2 | f
function NumPairs(f)
    n := 1;
    for fa in Factorization(f) do
        n *:= &+[ e+1 : e in [0..fa[2] div 2] ];
    end for;
    return n;
end function;

// value = < min(dX,dZ), dX, dZ, d1, window, rho, f, g, h, k >
// maxpairs: if there are more pairs (g,h) than this, a random sample of maxpairs pairs is used
function RunGalindo(q, degrees, fam, trials, minwindow : maxpairs := 300, fseqs := [])
    F := GF(q);
    Best := AssociativeArray();
    for m in degrees do
        N := 2*m;
        PP := PolynomialRing(F);
        if #fseqs gt 0 then
            flist := [ PP!sq : sq in fseqs | Degree(PP!sq) eq m ];
        else
            flist := FList(F, m, fam);
        end if;
        for f in flist do
            P := Parent(f);
            halfs := HalfDivisors(f);
            // list of pairs (g,h)
            pairs := [];
            if NumPairs(f) le maxpairs then
                for h in halfs do
                    for g in MonicDivisors(h) do Append(~pairs, <g, h>); end for;
                end for;
            else
                S := {};
                tries := 0;
                while #S lt maxpairs and tries lt 20*maxpairs do
                    h := Random(halfs); g := RandomSubDivisor(h);
                    Include(~S, <g, h>); tries +:= 1;
                end while;
                pairs := SetToSequence(S);
            end if;
            d1cache := AssociativeArray();
            for pr in pairs do
                g := pr[1]; h := pr[2];
                K := 2*(m - Degree(g) - Degree(h));
                if K le 0 then continue; end if;
                // synchronisation block <g>: best proper divisor g1 of g
                found := false; best1 := < 0, 0 >;
                for g1 in MonicDivisors(g) do
                    if Degree(g1) eq Degree(g) then continue; end if;
                    w := PolyOrder(g div g1);
                    if w lt minwindow then continue; end if;
                    if not IsDefined(d1cache, g1) then
                        d1cache[g1] := MinimumDistance(PolyCode(g1, f));
                    end if;
                    d1 := d1cache[g1];
                    if (not found) or d1 gt best1[1] or (d1 eq best1[1] and w gt best1[2]) then
                        best1 := < d1, w >; found := true;
                    end if;
                end for;
                if not found then continue; end if;
                for t in [1..trials] do
                    k := RandPoly(F, P, m);
                    X := QPCode([ [g, (k*g) mod f], [P!0, h] ], f, 2);
                    assert AnnDual(X, f, 2) subset X;             // Lemma lem:exp:annGalindo
                    dX := MinimumDistance(X);
                    dZ := MinimumDistance(Twist(X, f, 2));
                    key := < N, K, Family(f) >;
                    cand := < Min(dX, dZ), dX, dZ, best1[1], best1[2], Rho(f), f, g, h, k >;
                    if (not IsDefined(Best, key)) or IsBetter(cand, Best[key]) then
                        Best[key] := cand;
                    end if;
                end for;
            end for;
        end for;
    end for;
    return Best;
end function;

// Du-Ma-Liu, Table 1 (q, m, K, d): (a_l, a_r)-[[2m + a_l + a_r, K, d]]_q with a_l + a_r < m
// The last two targets (N = 250, 242) are expensive: run them separately.
procedure CompareDuMaLiu(trials)
    DML := [ <5, 25, 4, 4>, <7, 49, 28, 5>, <7, 49, 48, 5>, <5, 125, 4, 4>, <11, 121, 102, 7> ];
    for T in DML do
        q := T[1]; m := T[2]; K := T[3]; d := T[4];
        printf "--- target [[%o,%o,%o]]_%o (Du-Ma-Liu) ---\n", 2*m, K, d, q;
        for fam in [ "consta", "reptri" ] do
            B := RunGalindo(q, [m], fam, trials, 3);
            for key in Keys(B) do
                if key[2] eq K then
                    r := B[key];
                    printf "  %o: d=%o (dX=%o,dZ=%o) d1=%o window<%o rho=%o f=%o\n",
                           key[3], r[1], r[2], r[3], r[4], r[5], r[6], r[7];
                end if;
            end for;
        end for;
    end for;
end procedure;

// Save results of RunGalindo (keeps g, h AND k, so that every code can be rebuilt)
procedure SaveGalindo(Best, filename)
    keys := Sort(SetToSequence(Keys(Best)),
                 func< a, b | a[1] ne b[1] select a[1] - b[1] else a[2] - b[2] >);
    for key in keys do
        r := Best[key];
        fprintf filename, "[[%o,%o]] %o d=%o dX=%o dZ=%o d1=%o win=%o rho=%o f=%o\n  g=%o\n  h=%o\n  k=%o\n",
                key[1], key[2], key[3], r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[10];
    end for;
end procedure;
